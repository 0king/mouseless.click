#!/bin/sh
# Mouseless GNOME extension installer (per desktop user).
#
# Run from mouseless-workspace/ as your desktop user:
#   ./platform/install-extension.sh
#
# Packs the draw-only extension (extension.js + ipc.js + render.js + a
# generated config.js), installs it for the current user, and enables it.
# config.js is generated from mouseless.toml so the extension's socket path and
# legacy-payload appearance fallback match the daemon. On Wayland, log out and
# back in so GNOME Shell loads the new extension; on X11, Alt+F2 → r → Enter
# also works.
#
# Options:
#   --dry-run   print actions without installing
#   --help
set -eu

REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
EXT_DIR="$REPO_DIR/gnome-extension"
UUID="mouseless@0king.dev"
DRY_RUN=0

usage() {
    sed -n '2,/^set -eu$/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'
}

for arg in "$@"; do
    case "$arg" in
        --help|-h)
            usage
            exit 0
            ;;
        --dry-run) DRY_RUN=1 ;;
        *)
            echo "unknown option: $arg (try --help)" >&2
            exit 2
            ;;
    esac
done

if [ "$(id -u)" -eq 0 ]; then
    echo "run as your desktop user, not root: ./platform/install-extension.sh" >&2
    exit 1
fi

if ! command -v gnome-extensions >/dev/null 2>&1; then
    echo "gnome-extensions not found; install the GNOME Shell tools" >&2
    exit 1
fi

if [ ! -f "$EXT_DIR/metadata.json" ]; then
    echo "missing $EXT_DIR/metadata.json" >&2
    exit 1
fi

TOML="${MOUSELESS_CONFIG:-/etc/mouseless/mouseless.toml}"
if [ ! -f "$TOML" ]; then
    TOML="$REPO_DIR/mouseless.toml"
fi
if [ ! -f "$TOML" ]; then
    echo "missing $TOML; install the system files first" >&2
    exit 1
fi

toml_value() {
    sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*\"\([^\"]*\)\".*/\1/p" "$TOML" |
        head -n 1
}
toml_number() {
    sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*\([0-9][0-9.]*\).*/\1/p" "$TOML" |
        head -n 1
}

SOCKET_PATH="$(toml_value socket)"
GRID_COLOR="$(toml_value grid_color)"
GRID_OPACITY="$(toml_number grid_opacity)"
LABEL_COLOR="$(toml_value label_color)"
HIGHLIGHT_COLOR="$(toml_value highlight_color)"
for _value in "$SOCKET_PATH" "$GRID_COLOR" "$GRID_OPACITY" "$LABEL_COLOR" "$HIGHLIGHT_COLOR"; do
    if [ -z "$_value" ]; then
        echo "mouseless.toml is missing socket/color/opacity values" >&2
        exit 1
    fi
done
for _color in "$GRID_COLOR" "$LABEL_COLOR" "$HIGHLIGHT_COLOR"; do
    case "$_color" in
        \#??????) ;;
        *)
            echo "mouseless.toml colours must be #rrggbb, got $_color" >&2
            exit 1
            ;;
    esac
done

if ! grep -Fq "\"uuid\": \"$UUID\"" "$EXT_DIR/metadata.json"; then
    echo "metadata.json does not declare uuid $UUID" >&2
    exit 1
fi

run() {
    if [ "$DRY_RUN" -eq 1 ]; then
        printf '  + %s\n' "$*"
    else
        "$@"
    fi
}

PACK_DIR="$(mktemp -d)"
trap 'rm -rf "$PACK_DIR"' EXIT

if [ "$DRY_RUN" -eq 1 ]; then
    echo "mouseless: extension install (dry run) — no changes will be made"
else
    echo "mouseless: extension install"
fi

# Pack a copy so config.js can be generated without dirtying the checkout.
PACK_SRC="$PACK_DIR/src"
mkdir -p "$PACK_SRC"
cp "$EXT_DIR/extension.js" "$EXT_DIR/ipc.js" "$EXT_DIR/render.js" \
    "$EXT_DIR/metadata.json" "$PACK_SRC"/
cat >"$PACK_SRC/config.js" <<EOF
// Generated by platform/install-extension.sh from $TOML. Do not edit.
function hex(value) {
    const number = Number.parseInt(value.slice(1), 16);
    return [(number >> 16) & 0xff, (number >> 8) & 0xff, number & 0xff];
}

export const CONFIGURED_SOCKET_PATH = '$SOCKET_PATH';

export const CONFIGURED_APPEARANCE = {
    grid_color: hex('$GRID_COLOR'),
    grid_opacity: $GRID_OPACITY,
    label_color: hex('$LABEL_COLOR'),
    highlight_color: hex('$HIGHLIGHT_COLOR'),
};
EOF
run gnome-extensions pack "$PACK_SRC" --force -o "$PACK_DIR" \
    --extra-source=ipc.js --extra-source=render.js --extra-source=config.js
run gnome-extensions install --force "$PACK_DIR/$UUID.shell-extension.zip"

# `gnome-extensions install --force` unloads the old instance asynchronously and
# can add the UUID to the session's disabled-extensions list. While the UUID is
# in that list `gnome-extensions enable` exits 0 but is a silent no-op, leaving
# the extension INACTIVE. Wait for the unload, then drop our entry before
# enabling.
if [ "$DRY_RUN" -eq 0 ]; then
    sleep 2
    if gsettings get org.gnome.shell disabled-extensions 2>/dev/null \
        | grep -Fq "'$UUID'"; then
        echo "mouseless: removing $UUID from disabled-extensions"
        gsettings set org.gnome.shell disabled-extensions \
            "$(gsettings get org.gnome.shell disabled-extensions \
                | sed "s/'$UUID', //; s/, '$UUID'//; s/'$UUID'//")"
    fi
fi

if ! run gnome-extensions enable "$UUID"; then
    echo "extension installed but not enabled yet; after logging in run:" >&2
    echo "  gnome-extensions enable $UUID" >&2
fi

if [ "$DRY_RUN" -eq 1 ]; then
    echo "Dry run: extension $UUID would be installed."
else
    echo "Extension $UUID installed."
fi

cat <<EOF
On Wayland, log out and back in so GNOME Shell loads it.
Verify:
  gnome-extensions info $UUID
  gnome-extensions list --enabled
  systemctl status mouselessd.service
EOF
