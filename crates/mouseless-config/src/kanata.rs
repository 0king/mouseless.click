//! Kanata include rendering and the `kanata --check` gate (SPEC-settings).
//!
//! The renderer is pure: the same [`Config`] always produces the same include.
//! The checker stages a throwaway copy of the user's main kanata config plus
//! the candidate include, then runs `kanata --check --cfg <staged-main>`; it
//! never writes to `/etc` and needs no privileges. Installing the include is a
//! separate platform/privilege decision (SPEC-settings OQ-3).

use crate::schema::{Config, GridConfig};
use std::ffi::OsString;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Default include filename expected by `unicfg.kbd`.
pub const INCLUDE_NAME: &str = "mouseless.kbd";

/// Render the complete `mouseless.kbd` include for `config`.
///
/// The overlay layer always emits the full 30-key QWERTY block: grid columns
/// and rows are subsets interpreted by the daemon, so changing them never
/// requires a different physical mapping. Tap thresholds and layer names do
/// change the include.
pub fn render_include(config: &Config) -> String {
    let tap = config.behavior.tap_threshold_ms;
    let overlay = &config.keybindings.overlay_layer;
    let free = &config.keybindings.free_mode_layer;
    let grid = &config.grid;

    let mut out = String::new();
    out.push_str(
        ";; Mouseless overlay + custom free-mode layers for kanata (Phase 3).\n\
         ;; GENERATED by mouseless-config -- edit config.yaml, not this file.\n\
         ;; Installed as /etc/kanata/mouseless.kbd, sourced from unicfg.kbd via\n\
         ;;   (include \"mouseless.kbd\")\n\
         ;; Requires in unicfg.kbd (see UNICFG-EDITS.md):\n\
         ;; - lyr-base: lsft slot replaced with `@ml-tap` (overlay trigger)\n\
         ;; - lyr-base: lctl slot replaced with `@ml-free-tap` (free-mode trigger)\n\
         ;; - defcfg: linux-output-device-name + linux-dev-names-exclude\n",
    );
    out.push_str(&format!(
        "\n(defalias\n  ml-tap (tap-hold-release {tap} {tap} (layer-switch {overlay}) lsft)\n  ml-free-tap (tap-hold-release {tap} {tap} (layer-switch {free}) lctl)\n)\n"
    ));
    out.push_str(&format!(
        "\n(deflayer {overlay}\n  (layer-switch lyr-base) _ _ _ _ _ _ _ _ _ _ _ _\n  _ _ _ _ _ _ _ _ _ _ _ _ _ _\n  _ q w e r t y u i o p _ _ _\n  _ a s d f g h j k l ; _ _\n  lsft z x c v b n m , . / rsft\n  lctl lmet lalt spc ralt rctl rmet\n)\n"
    ));
    out.push_str(&format!(
        "\n(deflayer {free}\n  (layer-switch lyr-base) XX XX XX XX XX XX XX XX XX XX XX XX\n  XX XX XX XX XX XX XX XX XX XX XX XX XX XX\n  XX q w e r XX XX XX i XX XX XX XX XX\n  XX a s d f XX XX j k l XX XX XX\n  lsft XX XX XX XX XX XX m , . / rsft\n  lctl lmet lalt spc ralt rctl rmet\n)\n"
    ));

    // The header comment states the pools so a human editing the generated
    // file knows which subset is valid.
    let GridConfig { columns, rows, .. } = grid;
    out.push_str(&format!(
        "\n;; Config pools: columns={columns:?} rows={rows:?}\n"
    ));
    out
}

/// Result of running `kanata --check`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CheckOutput {
    /// Whether the process exited successfully.
    pub success: bool,
    /// Captured stdout.
    pub stdout: String,
    /// Captured stderr.
    pub stderr: String,
}

/// Injectable process runner so the check gate is hermetic in tests.
pub trait Runner {
    /// Run `program` with `args` and capture output.
    fn run(&mut self, program: &Path, args: &[OsString]) -> Result<CheckOutput, String>;
}

/// Real process runner (`std::process::Command`).
#[derive(Debug, Clone, Copy, Default)]
pub struct ProcessRunner;

impl Runner for ProcessRunner {
    fn run(&mut self, program: &Path, args: &[OsString]) -> Result<CheckOutput, String> {
        let output = Command::new(program)
            .args(args)
            .output()
            .map_err(|e| format!("spawn {}: {e}", program.display()))?;
        Ok(CheckOutput {
            success: output.status.success(),
            stdout: String::from_utf8_lossy(&output.stdout).into_owned(),
            stderr: String::from_utf8_lossy(&output.stderr).into_owned(),
        })
    }
}

/// `kanata --check` gate for a candidate include.
#[derive(Debug, Clone)]
pub struct KanataCheck {
    program: PathBuf,
    main_cfg: PathBuf,
    include_name: String,
}

impl KanataCheck {
    /// Standard layout: `/etc/kanata/unicfg.kbd` includes `mouseless.kbd`.
    pub fn new(program: impl Into<PathBuf>, main_cfg: impl Into<PathBuf>) -> Self {
        Self {
            program: program.into(),
            main_cfg: main_cfg.into(),
            include_name: INCLUDE_NAME.into(),
        }
    }

    /// Override the include filename (must match the main config's include).
    pub fn with_include_name(mut self, name: impl Into<String>) -> Self {
        self.include_name = name.into();
        self
    }

    /// Stage the candidate and run the real `kanata --check`.
    pub fn check(&self, candidate_include: &str) -> Result<(), CheckError> {
        self.check_with(candidate_include, &mut ProcessRunner)
    }

    /// Stage the candidate and run `runner` (used by tests).
    pub fn check_with<R: Runner>(
        &self,
        candidate_include: &str,
        runner: &mut R,
    ) -> Result<(), CheckError> {
        let staged = StagedConfig::create(&self.main_cfg, &self.include_name, candidate_include)?;
        let args = vec![
            OsString::from("--check"),
            OsString::from("--cfg"),
            staged.main_path().as_os_str().to_os_string(),
        ];
        let output = runner
            .run(&self.program, &args)
            .map_err(CheckError::Spawn)?;
        if output.success {
            Ok(())
        } else {
            Err(CheckError::Rejected {
                stdout: output.stdout,
                stderr: output.stderr,
            })
        }
    }
}

/// Check-gate failures (all GUI-presentable).
#[derive(Debug, thiserror::Error)]
pub enum CheckError {
    /// Staging or filesystem failure.
    #[error("kanata check setup: {0}")]
    Setup(String),
    /// The runner could not start the process.
    #[error("kanata check spawn: {0}")]
    Spawn(String),
    /// `kanata --check` exited non-zero.
    #[error("kanata --check rejected the config: {stderr}{stdout}")]
    Rejected {
        /// Captured stdout.
        stdout: String,
        /// Captured stderr.
        stderr: String,
    },
}

impl From<CheckError> for crate::ConfigError {
    fn from(value: CheckError) -> Self {
        crate::ConfigError::CheckFailed {
            message: value.to_string(),
        }
    }
}

/// Throwaway directory holding the staged main config + candidate include.
struct StagedConfig {
    dir: PathBuf,
    main: PathBuf,
}

impl StagedConfig {
    fn create(
        main_cfg: &Path,
        include_name: &str,
        candidate_include: &str,
    ) -> Result<Self, CheckError> {
        let main_text = std::fs::read_to_string(main_cfg)
            .map_err(|e| CheckError::Setup(format!("read {}: {e}", main_cfg.display())))?;
        let include_line = format!("(include \"{include_name}\")");
        if !main_text.contains(&include_line) {
            return Err(CheckError::Setup(format!(
                "{} does not contain {include_line}; cannot stage the candidate include",
                main_cfg.display()
            )));
        }

        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|duration| duration.as_nanos())
            .unwrap_or(0);
        let dir = std::env::temp_dir().join(format!(
            "mouseless-kanata-check-{}-{nanos}",
            std::process::id()
        ));
        std::fs::create_dir_all(&dir)
            .map_err(|e| CheckError::Setup(format!("mkdir {}: {e}", dir.display())))?;

        let main_name = main_cfg
            .file_name()
            .ok_or_else(|| CheckError::Setup("main config has no file name".into()))?;
        let main = dir.join(main_name);
        std::fs::write(&main, &main_text)
            .map_err(|e| CheckError::Setup(format!("write {}: {e}", main.display())))?;
        std::fs::write(dir.join(include_name), candidate_include)
            .map_err(|e| CheckError::Setup(format!("write candidate: {e}")))?;

        // Copy every other relative include the main config references so the
        // staged copy keeps the same include graph.
        for name in relative_includes(&main_text) {
            if name == include_name {
                continue;
            }
            let source = main_cfg
                .parent()
                .unwrap_or_else(|| Path::new("."))
                .join(&name);
            if source.exists() {
                let destination = dir.join(&name);
                if let Some(parent) = destination.parent() {
                    std::fs::create_dir_all(parent).map_err(|e| {
                        CheckError::Setup(format!("mkdir {}: {e}", parent.display()))
                    })?;
                }
                std::fs::copy(&source, &destination).map_err(|e| {
                    CheckError::Setup(format!(
                        "copy {} -> {}: {e}",
                        source.display(),
                        destination.display()
                    ))
                })?;
            }
        }

        Ok(Self { dir, main })
    }

    fn main_path(&self) -> &Path {
        &self.main
    }
}

impl Drop for StagedConfig {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.dir);
    }
}

/// Extract relative include names from a kanata config (`(include "x.kbd")`).
fn relative_includes(text: &str) -> Vec<String> {
    let mut names = Vec::new();
    let mut rest = text;
    while let Some(start) = rest.find("(include \"") {
        let after = &rest[start + "(include \"".len()..];
        if let Some(end) = after.find('"') {
            let name = &after[..end];
            if !name.starts_with('/') && !names.iter().any(|known| known == name) {
                names.push(name.to_string());
            }
            rest = &after[end..];
        } else {
            break;
        }
    }
    names
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::VecDeque;

    fn temp_dir(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "mouseless-kanata-{tag}-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    struct FakeRunner {
        outputs: VecDeque<CheckOutput>,
        seen_cfg: Option<PathBuf>,
    }

    impl Runner for FakeRunner {
        fn run(&mut self, _program: &Path, args: &[OsString]) -> Result<CheckOutput, String> {
            assert_eq!(args[0], "--check");
            assert_eq!(args[1], "--cfg");
            let cfg = PathBuf::from(&args[2]);
            let text = std::fs::read_to_string(&cfg).unwrap();
            let parent = cfg.parent().unwrap();
            // The candidate must be reachable through the staged include graph.
            let include = std::fs::read_to_string(parent.join(INCLUDE_NAME)).unwrap();
            assert!(include.contains("(deflayer"));
            assert!(text.contains("(include \"mouseless.kbd\")"));
            self.seen_cfg = Some(cfg);
            Ok(self.outputs.pop_front().unwrap())
        }
    }

    fn ok() -> CheckOutput {
        CheckOutput {
            success: true,
            stdout: "config file is valid".into(),
            stderr: String::new(),
        }
    }

    #[test]
    fn rendered_include_pins_the_fixed_layout_and_config_values() {
        let mut config = Config::default();
        config.behavior.tap_threshold_ms = 150;
        config.keybindings.overlay_layer = "lyr-overlay".into();
        config.keybindings.free_mode_layer = "lyr-move".into();
        let include = render_include(&config);
        assert!(
            include.contains("ml-tap (tap-hold-release 150 150 (layer-switch lyr-overlay) lsft)")
        );
        assert!(
            include.contains("ml-free-tap (tap-hold-release 150 150 (layer-switch lyr-move) lctl)")
        );
        assert!(include.contains("(deflayer lyr-overlay"));
        assert!(include.contains("(deflayer lyr-move"));
        assert!(include.contains("q w e r t y u i o p"));
        assert!(include.contains("a s d f g h j k l ;"));
        assert!(include.contains("z x c v b n m , . /"));
        assert!(include.contains("XX q w e r XX XX XX i XX"));
        assert!(include.contains("lyr-base"));
    }

    #[test]
    fn render_is_deterministic() {
        let config = Config::default();
        assert_eq!(render_include(&config), render_include(&config));
    }

    #[test]
    fn check_stages_main_and_candidate_and_accepts_success() {
        let dir = temp_dir("ok");
        let main = dir.join("unicfg.kbd");
        std::fs::write(&main, "(include \"mouseless.kbd\")\n(defsrc a)\n").unwrap();
        let config = Config::default();
        let include = render_include(&config);
        let mut runner = FakeRunner {
            outputs: VecDeque::from([ok()]),
            seen_cfg: None,
        };
        let check = KanataCheck::new("/usr/bin/kanata", &main);
        check.check_with(&include, &mut runner).unwrap();
        assert!(runner.seen_cfg.is_some());
        // The staged temp dir is removed after the check.
        let parent = runner.seen_cfg.as_ref().unwrap().parent().unwrap();
        assert!(!parent.exists());
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn check_returns_rejection_output() {
        let dir = temp_dir("reject");
        let main = dir.join("unicfg.kbd");
        std::fs::write(&main, "(include \"mouseless.kbd\")\n").unwrap();
        let mut runner = FakeRunner {
            outputs: VecDeque::from([CheckOutput {
                success: false,
                stdout: "some stdout".into(),
                stderr: "unknown key XX".into(),
            }]),
            seen_cfg: None,
        };
        let check = KanataCheck::new("/usr/bin/kanata", &main);
        let error = check
            .check_with(&render_include(&Config::default()), &mut runner)
            .unwrap_err();
        assert!(matches!(error, CheckError::Rejected { .. }));
        assert!(error.to_string().contains("unknown key XX"));
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn check_refuses_when_main_config_does_not_include_the_candidate() {
        let dir = temp_dir("missing-include");
        let main = dir.join("unicfg.kbd");
        std::fs::write(&main, "(defsrc a)\n").unwrap();
        let mut runner = FakeRunner {
            outputs: VecDeque::new(),
            seen_cfg: None,
        };
        let check = KanataCheck::new("/usr/bin/kanata", &main);
        let error = check
            .check_with(&render_include(&Config::default()), &mut runner)
            .unwrap_err();
        assert!(matches!(error, CheckError::Setup(_)));
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn relative_include_parser_ignores_absolute_and_duplicates() {
        let text = "(include \"a.kbd\")\n(include \"a.kbd\")\n(include \"/etc/b.kbd\")\n(include \"sub/c.kbd\")";
        assert_eq!(relative_includes(text), vec!["a.kbd", "sub/c.kbd"]);
    }
}
